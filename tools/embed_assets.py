"""Embed assets/*.txt into core/src/assets_data.c.

    python3 tools/embed_assets.py

docs/50 requires assets to stay plain text on disk and be *compiled into the
binary*, not loaded through a platform API. This keeps the text file the source
of truth (so `git diff` shows which pixels moved) while leaving the core with no
file I/O at all -- which is what makes it portable to WASM for free.

One row per C string literal, so the generated file is also readable and a
difference between the .txt and the .c is obvious.
"""

import sys
from pathlib import Path

ASSETS = Path("assets")
OUT = Path("core/src/assets_data.c")


def rows_of(path):
    lines = [ln.rstrip("\n") for ln in path.read_text().splitlines()]
    return [ln for ln in lines if ln and not ln.startswith("#")]


def emit_rows(name, rows, comment):
    out = [f"/* {comment} */", f"const char *const {name}[{len(rows)}] = {{"]
    for r in rows:
        out.append(f'    "{r}",')
    out.append("};")
    out.append(f"const int {name}_rows = {len(rows)};")
    out.append(f"const int {name}_cols = {len(rows[0])};")
    return "\n".join(out)


def parse_palette(path):
    cols = []
    for ln in path.read_text().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        _, _, hexv = ln.split()
        h = hexv.lstrip("#")
        cols.append((int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)))
    return cols


def main():
    panel = rows_of(ASSETS / "panel_c01.txt")
    depth = rows_of(ASSETS / "depth_c01.txt")
    wf = rows_of(ASSETS / "waterfall_c01.txt")
    pal = parse_palette(ASSETS / "palette_c01.txt")

    assert len(panel) == 270 and len(panel[0]) == 480, "panel must be 480x270"
    assert len(depth) == 270 and len(depth[0]) == 480
    assert len(wf) == 270 and len(wf[0]) == 480
    assert len(pal) == 24, f"expected 24 colours, got {len(pal)}"

    parts = [
        "/* GENERATED by tools/embed_assets.py -- do not edit by hand.",
        " * Source of truth: assets/panel_c01.txt, depth_c01.txt, waterfall_c01.txt,",
        " * palette_c01.txt. Regenerate after re-running the exporters.",
        " */",
        "",
        '#include "assets_data.h"',
        "",
        f"const int dr_palette_count = {len(pal)};",
        "const unsigned char dr_palette_rgb[][3] = {",
    ]
    for r, g, b in pal:
        parts.append(f"    {{{r:3d}, {g:3d}, {b:3d}}},")
    parts.append("};")
    parts.append("")

    parts.append(emit_rows("dr_panel_rows", panel,
                           "Palette indices, one base36 char per pixel."))
    parts.append("")
    parts.append(emit_rows("dr_depth_rows", depth,
                           "Depth quantised to base16: 0 = far, 15 = near."))
    parts.append("")
    parts.append(emit_rows("dr_wf_rows", wf,
                           "Waterfall mask: '.' none, '1' shimmer, '2' haze."))
    parts.append("")

    # Warm/cool ramp split, so the core can pick a 'cream' or an 'ink' step
    # without hard-coding an index that the exporter might renumber.
    cool = [i for i, (r, g, b) in enumerate(pal) if b >= r]
    warm = [i for i, (r, g, b) in enumerate(pal) if b < r]
    parts.append(f"const int dr_cool_first = {cool[0]};")
    parts.append(f"const int dr_cool_count = {len(cool)};")
    parts.append(f"const int dr_warm_first = {warm[0]};")
    parts.append(f"const int dr_warm_count = {len(warm)};")
    parts.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts) + "\n")

    hdr = ["/* GENERATED by tools/embed_assets.py -- do not edit by hand. */",
           "#ifndef ASSETS_DATA_H",
           "#define ASSETS_DATA_H",
           "",
           "#define DR_ASSET_W 480",
           "#define DR_ASSET_H 270",
           "",
           "extern const int dr_palette_count;",
           "extern const unsigned char dr_palette_rgb[][3];",
           "extern const char *const dr_panel_rows[270];",
           "extern const char *const dr_depth_rows[270];",
           "extern const char *const dr_wf_rows[270];",
           "extern const int dr_panel_rows_rows, dr_panel_rows_cols;",
           "extern const int dr_cool_first, dr_cool_count;",
           "extern const int dr_warm_first, dr_warm_count;",
           "",
           "#endif /* ASSETS_DATA_H */"]
    (OUT.parent / "assets_data.h").write_text("\n".join(hdr) + "\n")

    print(f"wrote {OUT} ({OUT.stat().st_size//1024} KB)")
    print(f"  palette {len(pal)}  cool {len(cool)} @{cool[0]}  warm {len(warm)} @{warm[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
